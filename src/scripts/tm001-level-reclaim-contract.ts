import {strict as assert} from "node:assert";
import {knownLevels,firstReclaim,forwardExcursion} from "../research/level-reclaim.js";
import type {MinuteBar} from "../market/types.js";
const base=Date.parse("2026-10-05T13:30:00Z");
const bar=(i:number,o:number,h:number,l:number,c:number):MinuteBar=>({contractTicker:"NQZ6",productCode:"NQ",timestampMs:base+i*60000,sessionEndDate:"2026-10-05",open:o,high:h,low:l,close:c,volume:100});
const day:MinuteBar[]=Array.from({length:30},(_,i)=>bar(i,100,101,99,100));
day[5]=bar(5,100,104,100,103);
day[6]=bar(6,103,104,100,101);
day[7]=bar(7,101,102,97,98);
const levels=knownLevels(day,[bar(-1,100,110,90,100)]);
assert.equal(levels.length,6);
assert.equal(levels.find(l=>l.kind==="ORB_5_HIGH")?.price,101);
assert.equal(levels.find(l=>l.kind==="ORB_5_HIGH")?.knownAtIndex,5);
const reclaim=firstReclaim(day,levels.find(l=>l.kind==="ORB_5_HIGH")!);
assert(reclaim);
assert.equal(reclaim.breakoutIndex,5);
assert.equal(reclaim.reclaimIndex,6);
assert.equal(reclaim.direction,"SHORT");
assert.equal(firstReclaim(day.slice(0,6),levels.find(l=>l.kind==="ORB_5_HIGH")!),null);
const forward=forwardExcursion(day,reclaim,1);
assert.equal(forward.forwardBars,1);
assert.equal(forward.maxFavorablePoints,4);
assert.equal(forward.maxAdversePoints,1);
assert.equal(forward.closeMovePoints,3);
assert.equal(forwardExcursion(day.slice(0,7),reclaim,1).forwardBars,0);
console.log("TM001 LEVEL RECLAIM CONTRACT GREEN 10/10 | ZERO_API | ZERO_TRADES");
