import {strict as assert} from "node:assert";
import type {MinuteBar} from "../market/types.js";
import type {KnownLevel} from "../research/level-reclaim.js";
import {firstWickRejection} from "../research/wick-rejection.js";
const base=Date.parse("2026-10-05T13:30:00Z");
const bar=(i:number,h:number,l:number,c:number):MinuteBar=>({contractTicker:"NQZ6",productCode:"NQ",timestampMs:base+i*60000,sessionEndDate:"2026-10-05",open:c,high:h,low:l,close:c,volume:100});
const high:KnownLevel={kind:"OVERNIGHT_HIGH",price:110,knownAtIndex:0,side:"HIGH"};
const low:KnownLevel={kind:"OVERNIGHT_LOW",price:90,knownAtIndex:0,side:"LOW"};
let checks=0;
