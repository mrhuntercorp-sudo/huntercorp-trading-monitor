import {strict as assert} from "node:assert";
import type {MinuteBar} from "../market/types.js";
import type {ReclaimEvent,KnownLevel} from "../research/level-reclaim.js";
import {reclaimHold,opposingLevelRoom} from "../research/reclaim-confirmation.js";
const base=Date.parse("2026-10-05T13:30:00Z");
const bar=(i:number,close:number,low=close-1,high=close+1):MinuteBar=>({contractTicker:"NQZ6",productCode:"NQ",timestampMs:base+i*60000,sessionEndDate:"2026-10-05",open:close,high,low,close,volume:100});
const day=[bar(0,98),bar(1,101),bar(2,102,98),bar(3,101,97),bar(4,99)];
const event:ReclaimEvent={kind:"ORB_5_LOW",price:100,breakoutIndex:0,reclaimIndex:1,breakoutClose:98,reclaimClose:101,direction:"LONG",reclaimTimestampMs:day[1]!.timestampMs};
let checks=0;
const eq=(a:unknown,b:unknown)=>{assert.deepEqual(a,b);checks++;};
eq(reclaimHold(day.slice(0,2),event,2).status,"PENDING");
eq(reclaimHold(day.slice(0,3),event,2).status,"PENDING");
eq(reclaimHold(day.slice(0,4),event,2).status,"HELD");
eq(reclaimHold(day, event,3).status,"FAILED");
eq(reclaimHold(day,event,3).failedAtIndex,4);
eq(reclaimHold(day.slice(0,4),event,2).observedBars,2);
eq(reclaimHold([bar(0,98),bar(1,101),bar(2,99)],event,2).status,"FAILED");
eq(reclaimHold([bar(0,98),bar(1,101),bar(2,100),bar(3,100)],event,2).status,"HELD");
assert.throws(()=>reclaimHold(day,event,0),/INVALID_CONFIRMATION_BARS/);checks++;
const levels:KnownLevel[]=[{kind:"OVERNIGHT_HIGH",price:110,knownAtIndex:0,side:"HIGH"},{kind:"ORB_5_HIGH",price:105,knownAtIndex:5,side:"HIGH"},{kind:"OVERNIGHT_LOW",price:90,knownAtIndex:0,side:"LOW"}];
eq(opposingLevelRoom(event,levels).roomPoints,9);
eq(opposingLevelRoom(event,levels).nearestOpposingKind,"OVERNIGHT_HIGH");
eq(opposingLevelRoom(event,[levels[1]!]).roomPoints,null);
const short:ReclaimEvent={...event,direction:"SHORT",price:100,reclaimClose:99};
eq(opposingLevelRoom(short,levels).roomPoints,9);
console.log("TM001 RECLAIM CONFIRMATION CONTRACT GREEN "+checks+"/"+checks+" | ZERO_API | ZERO_TRADES");
